"""Build a Power BI-ready NETWORK planning dataset from group-aware scenarios.

This is an engineering-screening output, NOT an investment recommendation.
It makes no financial, growth, DSO, or revenue assumptions. All values are
scenario-model estimates, and evidence status is retained in every output.

Run from the project root:
    python src\build_cpo_network_planning_dataset.py

Input files (generated by the two previous steps):
    data/processed/registry_network_expansion_scenarios.csv
    data/processed/registry_network_simulation_results.csv

Output files (new; older simulations/business cases untouched):
    data/processed/cpo_network_planning_scenarios.csv
    data/processed/cpo_network_planning_sites.csv
"""
from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
PROCESSED = ROOT / "data" / "processed"
SCENARIOS = PROCESSED / "registry_network_expansion_scenarios.csv"
SIMULATIONS = PROCESSED / "registry_network_simulation_results.csv"
OUTPUT_SCENARIOS = PROCESSED / "cpo_network_planning_scenarios.csv"
OUTPUT_SITES = PROCESSED / "cpo_network_planning_sites.csv"

SCENARIO_FIELDS = {
    "scenario_id", "site_id", "city", "scenario_type", "current_chargers",
    "scenario_chargers", "additional_chargers", "current_connectors",
    "scenario_connectors", "scenario_simultaneous_positions", "scenario_grid_kw",
    "grid_limit_source", "grid_evidence_status", "equipment_evidence_statuses",
    "engineering_review_status", "decision_readiness",
}
SIMULATION_FIELDS = {
    "scenario_id", "site_id", "scenario_type", "scenario_chargers",
    "scenario_connectors", "arrivals", "cars_served", "cars_rejected",
    "rejected_pct", "energy_requested_kwh", "energy_delivered_kwh",
    "total_unserved_energy_kwh", "energy_shortfall_served_kwh",
    "average_occupied_minutes", "peak_site_grid_draw_kw",
    "minutes_at_grid_limit", "minutes_shared_pool_limited",
    "investment_readiness",
}


def read_csv(path: Path, required: set[str], label: str) -> pd.DataFrame:
    if not path.is_file():
        raise FileNotFoundError(f"Missing {label}: {path}. Run the preceding project step first.")
    frame = pd.read_csv(path, dtype={"scenario_id": "string", "site_id": "string"})
    frame.columns = frame.columns.str.strip()
    missing = sorted(required.difference(frame.columns))
    if missing:
        raise ValueError(f"{label} missing required columns: {missing}")
    if frame.empty:
        raise ValueError(f"{label} contains no data")
    if frame[["site_id", "scenario_id"]].isna().any().any():
        raise ValueError(f"{label}: missing site_id/scenario_id")
    if frame.duplicated("scenario_id").any():
        raise ValueError(f"{label}: duplicate scenario IDs")
    return frame


def numeric(frame: pd.DataFrame, columns: list[str], label: str) -> None:
    for column in columns:
        frame[column] = pd.to_numeric(frame[column], errors="coerce")
        if frame[column].isna().any() or not np.isfinite(frame[column]).all():
            raise ValueError(f"{label}: missing or invalid numeric values in {column}")


def assert_near(left: pd.Series, right: pd.Series, name: str, tolerance: float = 0.15) -> None:
    invalid = (left - right).abs() > tolerance
    if invalid.any():
        raise ValueError(f"Mismatch between scenario and simulation for {name}; check source data")


def build(scenarios: pd.DataFrame, simulations: pd.DataFrame) -> tuple[pd.DataFrame, pd.DataFrame]:
    # Enforce a single current baseline per site and matching scenario catalogs.
    scenarios = scenarios.copy()
    simulations = simulations.copy()
    if set(scenarios.scenario_id) != set(simulations.scenario_id):
        missing_simulations = sorted(set(scenarios.scenario_id) - set(simulations.scenario_id))
        unexpected_simulations = sorted(set(simulations.scenario_id) - set(scenarios.scenario_id))
        raise ValueError(
            "Scenario/simulation IDs do not match. Regenerate BOTH files. "
            f"Missing simulations: {missing_simulations[:5]}; unexpected: {unexpected_simulations[:5]}"
        )

    numeric(scenarios, ["current_chargers", "scenario_chargers", "additional_chargers",
                       "current_connectors", "scenario_connectors", "scenario_simultaneous_positions",
                       "scenario_grid_kw"], "scenario catalog")
    numeric(simulations, ["scenario_chargers", "scenario_connectors", "arrivals",
                          "cars_served", "cars_rejected", "rejected_pct", "energy_requested_kwh",
                          "energy_delivered_kwh", "total_unserved_energy_kwh",
                          "energy_shortfall_served_kwh", "average_occupied_minutes",
                          "peak_site_grid_draw_kw", "minutes_at_grid_limit",
                          "minutes_shared_pool_limited"], "simulation results")

    baseline = scenarios[scenarios.scenario_type == "CURRENT"]
    counts = baseline.groupby("site_id").size()
    all_sites = set(scenarios.site_id)
    if set(counts.index) != all_sites or (counts != 1).any():
        raise ValueError("Exactly one CURRENT scenario must exist per site")
    if not simulations.groupby("site_id").arrivals.nunique().eq(1).all():
        raise ValueError("Each site's scenarios must use the same number of vehicle arrivals")
    if not simulations.groupby("site_id").energy_requested_kwh.agg(lambda x: x.max() - x.min()).le(0.15).all():
        raise ValueError("Each site's scenarios must use the same requested energy")
    if (simulations.cars_served + simulations.cars_rejected != simulations.arrivals).any():
        raise ValueError("Served + rejected cars must equal arrivals")
    assert_near(simulations.energy_requested_kwh,
                simulations.energy_delivered_kwh + simulations.total_unserved_energy_kwh,
                "energy conservation", tolerance=0.2)

    merged = scenarios.merge(
        simulations.drop(columns=["scenario_type", "scenario_chargers", "scenario_connectors"]),
        on=["site_id", "scenario_id"], validate="one_to_one", suffixes=("", "_sim")
    )
    if len(merged) != len(scenarios) or (merged["scenario_grid_kw"] < merged["peak_site_grid_draw_kw"] - 0.05).any():
        raise ValueError("Missing joined scenarios or site grid limit violated")
    if "city_sim" in merged.columns and not (merged.city == merged.city_sim).all():
        raise ValueError("Site city mismatch between files")

    base_cols = ["site_id", "cars_rejected", "rejected_pct", "cars_served",
                 "energy_delivered_kwh", "total_unserved_energy_kwh", "arrivals"]
    base = merged[merged.scenario_type == "CURRENT"][base_cols].rename(columns={
        "cars_rejected": "baseline_cars_rejected",
        "rejected_pct": "baseline_rejected_pct",
        "cars_served": "baseline_cars_served",
        "energy_delivered_kwh": "baseline_energy_delivered_kwh",
        "total_unserved_energy_kwh": "baseline_total_unserved_energy_kwh",
        "arrivals": "baseline_arrivals",
    })
    merged = merged.merge(base, on="site_id", validate="many_to_one")

    merged["additional_cars_served"] = merged.cars_served - merged.baseline_cars_served
    merged["additional_energy_delivered_kwh"] = (
        merged.energy_delivered_kwh - merged.baseline_energy_delivered_kwh
    ).round(1)
    merged["reduction_in_unserved_energy_kwh"] = (
        merged.baseline_total_unserved_energy_kwh - merged.total_unserved_energy_kwh
    ).round(1)
    merged["rejected_rate_reduction_pp"] = (
        merged.baseline_rejected_pct - merged.rejected_pct
    ).round(2)
    merged["share_of_arrivals_newly_served_pct"] = (
        100 * merged.additional_cars_served / merged.arrivals
    ).round(2)

    # Do not convert simulated improvements into investment or grid approvals.
    merged["engineering_screening_result"] = np.select(
        [merged.scenario_type.eq("CURRENT"),
         (merged.additional_cars_served > 0) | (merged.additional_energy_delivered_kwh > 0.15),
         (merged.additional_cars_served < 0) | (merged.additional_energy_delivered_kwh < -0.15)],
        ["CURRENT_BASELINE", "SIMULATED_SERVICE_IMPROVEMENT", "SIMULATED_SERVICE_DECLINE"],
        default="NO_MEASURABLE_CHANGE_IN_TEST_PERIOD"
    )
    merged["data_validation_status"] = "MODEL_OUTPUT_NOT_FIELD_VALIDATED"
    merged["investment_decision"] = "EVIDENCE_REQUIRED_NOT_ASSESSED"
    merged["planning_note"] = (
        "Synthetic/historical scenario screening. No verified site economics, "
        "demand growth, DSO confirmation or real-world charger availability."
    )

    # Site-level overview: show ranges of technical benefits, NOT a 'best investment'.
    rows = []
    for site_id, group in merged.groupby("site_id", sort=True):
        current = group.loc[group.scenario_type == "CURRENT"].iloc[0]
        alternatives = group.loc[group.scenario_type != "CURRENT"]
        rows.append({
            "site_id": site_id,
            "city": current["city"],
            "current_chargers": int(current.current_chargers),
            "current_connectors": int(current.current_connectors),
            "current_grid_kw": float(current.scenario_grid_kw),
            "evaluated_expansion_options": int(len(alternatives)),
            "historical_arrivals_tested": int(current.arrivals),
            "baseline_cars_rejected": int(current.cars_rejected),
            "baseline_rejected_pct": float(current.rejected_pct),
            "maximum_additional_cars_served_across_options": int(
                max([0] + alternatives.additional_cars_served.tolist())
            ),
            "maximum_additional_energy_kwh_across_options": round(float(
                max([0] + alternatives.additional_energy_delivered_kwh.tolist())), 1
            ),
            "options_with_simulated_improvement": int((
                alternatives.engineering_screening_result == "SIMULATED_SERVICE_IMPROVEMENT"
            ).sum()),
            "grid_evidence_status": current.grid_evidence_status,
            "equipment_evidence_statuses": current.equipment_evidence_statuses,
            "data_validation_status": "MODEL_OUTPUT_NOT_FIELD_VALIDATED",
            "investment_decision": "EVIDENCE_REQUIRED_NOT_ASSESSED",
        })
    sites = pd.DataFrame(rows)
    order = ["site_id", "city", "scenario_id", "scenario_type", "expanded_group_id",
             "current_chargers", "scenario_chargers", "additional_chargers", "current_connectors",
             "scenario_connectors", "scenario_simultaneous_positions", "scenario_grid_kw",
             "grid_limit_source", "grid_evidence_status", "equipment_evidence_statuses",
             "engineering_review_status", "arrivals", "baseline_cars_rejected", "cars_rejected",
             "baseline_rejected_pct", "rejected_pct", "additional_cars_served",
             "share_of_arrivals_newly_served_pct", "baseline_energy_delivered_kwh",
             "energy_delivered_kwh", "additional_energy_delivered_kwh",
             "baseline_total_unserved_energy_kwh", "total_unserved_energy_kwh",
             "reduction_in_unserved_energy_kwh", "peak_site_grid_draw_kw", "minutes_at_grid_limit",
             "minutes_shared_pool_limited", "engineering_screening_result",
             "data_validation_status", "investment_decision", "planning_note"]
    extra = [c for c in merged.columns if c not in order]
    return merged[order + extra].sort_values(["site_id", "scenario_chargers", "scenario_id"]), sites


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--scenarios", type=Path, default=SCENARIOS)
    parser.add_argument("--simulations", type=Path, default=SIMULATIONS)
    parser.add_argument("--output-scenarios", type=Path, default=OUTPUT_SCENARIOS)
    parser.add_argument("--output-sites", type=Path, default=OUTPUT_SITES)
    args = parser.parse_args()
    if args.output_scenarios.resolve() == args.output_sites.resolve():
        raise ValueError("Output files must be different")

    scenarios = read_csv(args.scenarios, SCENARIO_FIELDS, "scenario catalog")
    simulations = read_csv(args.simulations, SIMULATION_FIELDS, "group-aware simulation")
    detail, sites = build(scenarios, simulations)
    for path, frame in ((args.output_scenarios, detail), (args.output_sites, sites)):
        path.parent.mkdir(parents=True, exist_ok=True)
        frame.to_csv(path, index=False)

    print("\n--- CPO NETWORK PLANNING DATASET ---")
    print(f"Sites: {len(sites)} | Scenarios: {len(detail)} | Model status: ENGINEERING DEMO")
    print(sites[["city", "current_chargers", "evaluated_expansion_options",
                 "baseline_cars_rejected", "maximum_additional_cars_served_across_options",
                 "maximum_additional_energy_kwh_across_options",
                 "investment_decision"]].to_string(index=False))
    print("\nNo financial ranking, grid-upgrade approval or investment recommendation was inferred.")
    print(f"Saved scenario dataset: {args.output_scenarios}")
    print(f"Saved site summary: {args.output_sites}")


if __name__ == "__main__":
    main()
