r"""Descriptive real-vs-synthetic charging occupancy screen for German DC sites.

Usage from the CPO Network Development project folder:
    python src\compare_real_dc_parks_with_simulation.py

Inputs (already generated by earlier project scripts):
    data/processed/german_dc_park_group_review.csv
    data/processed/german_dc_park_time_aligned_occupancy.csv
    data/processed/site_hourly_demand.csv

Outputs:
    data/processed/cpo_dc_park_occupancy_comparison.csv
    data/processed/cpo_dc_park_hourly_comparison.csv
    data/processed/cpo_dc_park_matched_candidates.csv

Real = irregular 2026 occupancy snapshots from POSSIBLE co-located installations.
Synthetic = 2025 hourly average connected cars / connector count.
No park boundary is verified. This does NOT validate rejected cars, demand,
charging duration, energy, charging power, waiting times, or investment value.
"""
from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import pandas as pd


READINESS = "DESCRIPTIVE_COMPARISON_MANUAL_SITE_CHECK_REQUIRED"
STRONG_LOCATION = "STRONG_COLOCATION_CANDIDATE"


def load_csv(path: Path, fields: list[str]) -> pd.DataFrame:
    if not path.is_file():
        raise FileNotFoundError(f"Missing: {path}\nRun the previous validation script first.")
    table = pd.read_csv(path, low_memory=False)
    table.columns = table.columns.str.strip()
    missing = sorted(set(fields) - set(table.columns))
    if missing:
        raise ValueError(f"{path.name} is missing {missing}")
    return table


def numeric(df: pd.DataFrame, columns: list[str]) -> None:
    for column in columns:
        df[column] = pd.to_numeric(df[column], errors="coerce")


def classify_power(kw: float) -> str:
    if pd.isna(kw):
        return "UNKNOWN"
    if kw >= 300:
        return "300_PLUS"
    if kw >= 150:
        return "150_TO_299"
    if kw >= 50:
        return "50_TO_149"
    return "BELOW_50"


def median_or_nan(series: pd.Series) -> float:
    return round(float(series.median()), 2) if series.notna().any() else np.nan


def prepare_simulation(path: Path) -> tuple[pd.DataFrame, pd.DataFrame]:
    sim = load_csv(path, [
        "site_id", "city", "hour", "connector_count", "charger_power_kw",
        "average_connected_vehicles",
    ])
    numeric(sim, ["connector_count", "charger_power_kw", "average_connected_vehicles"])
    sim["hour"] = pd.to_datetime(sim["hour"], errors="coerce")
    sim = sim.loc[
        sim["hour"].notna() & sim["connector_count"].gt(0)
        & sim["charger_power_kw"].gt(0)
        & sim["average_connected_vehicles"].ge(0)
        & sim["average_connected_vehicles"].le(sim["connector_count"] + 0.00001)
    ].copy()
    if sim.empty:
        raise ValueError("No valid simulated hourly occupancy records")
    sim["synthetic_occupancy_pct"] = 100 * sim["average_connected_vehicles"] / sim["connector_count"]
    sim["local_hour"] = sim["hour"].dt.hour
    sites = sim.groupby(["site_id", "city"], as_index=False).agg(
        simulated_connectors=("connector_count", "first"),
        charger_power_kw=("charger_power_kw", "first"),
        synthetic_hour_count=("synthetic_occupancy_pct", "size"),
        synthetic_mean_occupancy_pct=("synthetic_occupancy_pct", "mean"),
    )
    for _, s in sites.iterrows():
        sub = sim.loc[sim.site_id.eq(s.site_id)]
        if sub.connector_count.nunique() != 1 or sub.charger_power_kw.nunique() != 1:
            raise ValueError(f"Hardware configuration changes within hourly site {s.site_id}")
    sites["simulated_connectors"] = sites["simulated_connectors"].astype(int)
    sites["simulated_power_band"] = sites["charger_power_kw"].map(classify_power)
    sites["synthetic_mean_occupancy_pct"] = sites["synthetic_mean_occupancy_pct"].round(2)
    syn_hourly = sim.groupby(["site_id", "local_hour"], as_index=False).agg(
        synthetic_occupancy_pct=("synthetic_occupancy_pct", "mean"),
        synthetic_hourly_records=("synthetic_occupancy_pct", "size"),
    )
    return sites, syn_hourly


def prepare_real(review_path: Path, snapshots_path: Path,
                 min_windows: int, min_days: int) -> tuple[pd.DataFrame, pd.DataFrame]:
    parks = load_csv(review_path, [
        "park_candidate_id", "registered_points_combined", "member_power_bands",
        "location_check", "comparison_readiness", "park_identity",
        "synchronized_windows", "synchronized_days",
    ])
    numeric(parks, ["registered_points_combined", "synchronized_windows", "synchronized_days"])
    parks["park_candidate_id"] = parks["park_candidate_id"].astype("string").str.strip()
    if parks.park_candidate_id.isna().any() or parks.park_candidate_id.duplicated().any():
        raise ValueError("Park candidate IDs must be present and unique")
    # Only one rated-power class across all grouped installations; mixed
    # hardware groups cannot be called comparable to uniform simulated hardware.
    parks["single_power_band"] = parks["member_power_bands"].astype("string").str.strip()
    parks["single_power_band"] = parks["single_power_band"].where(
        ~parks["single_power_band"].str.contains("|", regex=False, na=True), "MIXED"
    )
    usable = parks.loc[
        parks["comparison_readiness"].eq(READINESS)
        & parks["location_check"].eq(STRONG_LOCATION)
        & parks["park_identity"].eq("POTENTIAL_GROUP_NOT_CONFIRMED")
        & parks["synchronized_windows"].ge(min_windows)
        & parks["synchronized_days"].ge(min_days)
        & parks["registered_points_combined"].gt(0)
        & parks["single_power_band"].ne("MIXED")
    ].copy()
    if usable.empty:
        raise ValueError("No strong co-location candidates meet data-quality thresholds")

    snapshots = load_csv(snapshots_path, [
        "park_candidate_id", "window_unix", "local_hour", "local_date",
        "snapshot_occupancy_pct", "no_free_reported", "total",
    ])
    snapshots["park_candidate_id"] = snapshots.park_candidate_id.astype("string").str.strip()
    numeric(snapshots, ["window_unix", "local_hour", "snapshot_occupancy_pct", "no_free_reported", "total"])
    snapshots = snapshots.loc[
        snapshots.park_candidate_id.isin(usable.park_candidate_id)
        & snapshots.local_hour.between(0, 23)
        & snapshots.snapshot_occupancy_pct.between(0, 100)
        & snapshots.no_free_reported.isin([0, 1])
        & snapshots.total.gt(0)
        & snapshots.window_unix.notna()
    ].copy()
    snapshots = snapshots.drop_duplicates(["park_candidate_id", "window_unix"], keep="last")
    if snapshots.empty:
        raise ValueError("No valid aligned snapshots found for qualifying park candidates")
    # Re-check actual snapshot counts and days (not just the park summary).
    coverage = snapshots.groupby("park_candidate_id", as_index=False).agg(
        valid_aligned_windows=("window_unix", "size"),
        valid_aligned_days=("local_date", "nunique"),
        real_mean_snapshot_occupancy_pct=("snapshot_occupancy_pct", "mean"),
        real_no_free_snapshot_pct=("no_free_reported", lambda s: 100 * s.mean()),
    )
    usable = usable.merge(coverage, how="inner", on="park_candidate_id", validate="one_to_one")
    usable = usable.loc[
        usable.valid_aligned_windows.ge(min_windows)
        & usable.valid_aligned_days.ge(min_days)
    ].copy()
    snapshots = snapshots.loc[snapshots.park_candidate_id.isin(usable.park_candidate_id)].copy()
    if usable.empty:
        raise ValueError("No parks have enough valid aligned snapshots after rechecking")
    return usable, snapshots


def calculate_comparison(sites: pd.DataFrame, syn_hour: pd.DataFrame,
                         real: pd.DataFrame, snapshots: pd.DataFrame,
                         min_parks: int, near_points: int):
    overview, hourly_output, candidates = [], [], []
    for site in sites.to_dict("records"):
        sid = site["site_id"]
        n = int(site["simulated_connectors"])
        band = site["simulated_power_band"]
        compatible = real.loc[real.single_power_band.eq(band)]
        exact = compatible.loc[compatible.registered_points_combined.eq(n)].copy()
        near = compatible.loc[
            compatible.registered_points_combined.between(max(1, n-near_points), n+near_points)
            & ~compatible.registered_points_combined.eq(n)
        ].copy()
        # Only exact point-count matches are used for the PRIMARY occupancy comparison.
        comparison_status = (
            "DESCRIPTIVE_SAMPLE_MANUAL_PARK_VERIFICATION_REQUIRED" if len(exact) >= min_parks
            else "TOO_FEW_EXACT_PARK_MATCHES" if len(exact) > 0
            else "NO_EXACT_PARK_MATCHES"
        )
        med = median_or_nan(exact.real_mean_snapshot_occupancy_pct)
        if len(exact) and pd.notna(med):
            gap = round(site["synthetic_mean_occupancy_pct"] - med, 2)
        else:
            gap = np.nan
        overview.append({
            "site_id": sid, "simulated_city": site["city"],
            "simulated_connectors": n, "simulated_power_band": band,
            "synthetic_hour_count_2025": site["synthetic_hour_count"],
            "synthetic_mean_hourly_occupancy_pct_2025": site["synthetic_mean_occupancy_pct"],
            "exact_potential_park_count": len(exact),
            "near_but_not_exact_park_count": len(near),
            "real_exact_park_median_snapshot_occupancy_pct_2026": med,
            "descriptive_gap_synthetic_minus_real_percentage_points": gap,
            "real_exact_park_median_no_free_snapshot_pct_2026": median_or_nan(exact.real_no_free_snapshot_pct),
            "comparison_status": comparison_status,
            "investment_readiness": "NOT_VALIDATED_DO_NOT_INVEST_FROM_THIS_TABLE",
        })
        for selection, group in [("EXACT", exact), ("NEAR_COUNT_NOT_EXACT", near)]:
            for p in group.to_dict("records"):
                candidates.append({
                    "site_id": sid, "simulated_city": site["city"],
                    "match_level": selection, "park_candidate_id": p["park_candidate_id"],
                    "registered_park_city": p.get("city", ""),
                    "registered_points_combined": int(p["registered_points_combined"]),
                    "member_installations": p.get("member_installations", np.nan),
                    "power_band": p["single_power_band"],
                    "aligned_snapshots": int(p["valid_aligned_windows"]),
                    "aligned_days": int(p["valid_aligned_days"]),
                    "real_mean_snapshot_occupancy_pct": round(p["real_mean_snapshot_occupancy_pct"], 2),
                    "real_no_free_snapshot_pct": round(p["real_no_free_snapshot_pct"], 2),
                    "park_identity": "POTENTIAL_UNCONFIRMED",
                })
        if exact.empty:
            continue
        relevant = snapshots.loc[snapshots.park_candidate_id.isin(exact.park_candidate_id)]
        # First calculate each park's hour-of-day mean. Then give every park equal
        # weight, so frequent reporters don't dominate the real-world profile.
        per_park = relevant.groupby(["park_candidate_id", "local_hour"], as_index=False).agg(
            per_park_mean_snapshot_occupancy_pct=("snapshot_occupancy_pct", "mean"),
            snapshots_in_hour=("snapshot_occupancy_pct", "size"),
        )
        real_hour = per_park.groupby("local_hour", as_index=False).agg(
            real_parks_reporting_hour=("park_candidate_id", "nunique"),
            real_equal_park_weighted_mean_snapshot_occupancy_pct=("per_park_mean_snapshot_occupancy_pct", "mean"),
        )
        both = syn_hour.loc[syn_hour.site_id.eq(sid)].merge(real_hour, on="local_hour", how="left")
        for row in both.to_dict("records"):
            real_count = row.get("real_parks_reporting_hour", np.nan)
            real_mean = row.get("real_equal_park_weighted_mean_snapshot_occupancy_pct", np.nan)
            hourly_output.append({
                "site_id": sid, "simulated_city": site["city"], "hour_of_day": int(row["local_hour"]),
                "synthetic_2025_mean_hourly_occupancy_pct": round(row["synthetic_occupancy_pct"], 2),
                "real_2026_equal_park_weighted_snapshot_occupancy_pct": round(real_mean, 2) if pd.notna(real_mean) else np.nan,
                "real_potential_parks_reporting_hour": int(real_count) if pd.notna(real_count) else 0,
                "comparison_status": comparison_status,
            })
    return (pd.DataFrame(overview), pd.DataFrame(hourly_output),
            pd.DataFrame(candidates, columns=[
                "site_id", "simulated_city", "match_level", "park_candidate_id",
                "registered_park_city", "registered_points_combined", "member_installations",
                "power_band", "aligned_snapshots", "aligned_days",
                "real_mean_snapshot_occupancy_pct", "real_no_free_snapshot_pct", "park_identity",
            ]))


def main() -> None:
    p = argparse.ArgumentParser(description="Descriptive German DC occupancy comparison")
    p.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    p.add_argument("--min-aligned-windows", type=int, default=24)
    p.add_argument("--min-aligned-days", type=int, default=7)
    p.add_argument("--min-comparable-parks", type=int, default=5)
    p.add_argument("--near-point-tolerance", type=int, default=2)
    args = p.parse_args()
    if min(args.min_aligned_windows, args.min_aligned_days, args.min_comparable_parks) < 1:
        p.error("Minimum observation/park thresholds must be positive")
    if not 0 <= args.near_point_tolerance <= 5:
        p.error("Near point tolerance must be 0–5")
    out = args.root.resolve() / "data" / "processed"
    sites, syn_hour = prepare_simulation(out / "site_hourly_demand.csv")
    real, snapshots = prepare_real(
        out / "german_dc_park_group_review.csv",
        out / "german_dc_park_time_aligned_occupancy.csv",
        args.min_aligned_windows, args.min_aligned_days,
    )
    overview, hours, candidates = calculate_comparison(
        sites, syn_hour, real, snapshots,
        args.min_comparable_parks, args.near_point_tolerance,
    )
    out.mkdir(parents=True, exist_ok=True)
    paths = [
        out / "cpo_dc_park_occupancy_comparison.csv",
        out / "cpo_dc_park_hourly_comparison.csv",
        out / "cpo_dc_park_matched_candidates.csv",
    ]
    for df, path in zip((overview, hours, candidates), paths):
        df.to_csv(path, index=False)
    print("\n--- REAL VS SYNTHETIC DC PARK OCCUPANCY ---")
    print(f"Strong-location potential parks with usable data: {len(real):,}")
    print(f"Simulated sites: {len(sites):,} | Aligned real snapshots: {len(snapshots):,}")
    print(overview[[
        "simulated_city", "simulated_connectors", "simulated_power_band",
        "synthetic_mean_hourly_occupancy_pct_2025", "exact_potential_park_count",
        "real_exact_park_median_snapshot_occupancy_pct_2026", "comparison_status",
    ]].to_string(index=False))
    print("\nSaved:")
    for path in paths:
        print(path)
    print("\nIMPORTANT: Real = irregular 2026 snapshots at UNCONFIRMED possible parks.")
    print("Synthetic = hourly 2025 averages at DIFFERENT fictional sites.")
    print("No verified demand forecast, rejection rate, grid value or ROI is inferred.")
    print("Near-point matches are provided for investigation, never mixed into exact benchmarks.")


if __name__ == "__main__":
    main()
