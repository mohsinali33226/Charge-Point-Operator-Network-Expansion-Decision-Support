"""Run configurable CPO charger-group expansion scenarios (engineering DEMO).

Reads the two CSVs generated by generate_network_scenarios.py, plus the
independent power-pool registry and historical arrival attempts.

Works with mixed charging unit configurations:
* arbitrary physical units and connectors per unit,
* a configurable limit on simultaneous sessions per unit,
* per-connector, per-unit, shared-power-pool and site-import power limits,
* unchanged vehicle arrivals between scenarios for a fair comparison.

This is not operationally validated CPO software. Session stays, charge curves,
charging efficiency, arrival behavior and any unverified data are illustrative.
No queues, transformer kVA / power-factor physics, real-time OCPP, failures,
capital expenditure or electricity procurement are modeled here.

Run: python src\\simulate_registry_network.py
Produces NEW CSVs, preserving older scenario and financial results.
"""
