# These are explicit DEMO behavior assumptions, not German CPO market values.
CHARGING_EFFICIENCY = 0.95
MAX_STAY_MULTIPLIER = 1.5
MAX_STAY_MINUTES = 120
RANDOM_SEED = 42
EPS = 1e-7
MINUTE = pd.Timedelta(minutes=1)


def read_required(path: Path, columns: set[str], label: str) -> pd.DataFrame:
    if not path.is_file():
        raise FileNotFoundError(f"Missing {label}: {path}")
    frame = pd.read_csv(path, dtype=str, keep_default_na=False)
    frame.columns = frame.columns.str.strip()
    missing = columns - set(frame.columns)
    if missing:
        raise ValueError(f"{label} missing columns: {sorted(missing)}")
    for col in frame.columns:
        frame[col] = frame[col].str.strip()
    return frame


def require_number(value: object, label: str, *, zero_ok: bool = False, integer: bool = False) -> float | int:
    try:
        n = float(str(value).strip())
    except (TypeError, ValueError) as exc:
        raise ValueError(f"{label} should be numeric, found {value!r}") from exc
    if not isfinite(n) or (n < 0 if zero_ok else n <= 0):
        raise ValueError(f"{label} must be {'nonnegative' if zero_ok else 'positive'}: {value!r}")
    if integer and not n.is_integer():
        raise ValueError(f"{label} must be an integer: {value!r}")
    return int(n) if integer else n


def fair_allocation(caps: list[float], budget: float) -> list[float]:
    """Water-fill: share a single power budget, unused shares redistributed."""
    if not caps:
        return []
    if budget <= 0:
        return [0.] * len(caps)
    if sum(caps) <= budget + EPS:
        return list(caps)
    remaining = set(range(len(caps)))
    allocation = [0.] * len(caps)
    available = float(budget)
    while remaining:
        share = available / len(remaining)
        limited = [i for i in remaining if caps[i] <= share + EPS]
        if limited:
            for i in limited:
                allocation[i] = caps[i]
                available -= caps[i]
                remaining.remove(i)
        else:
            for i in remaining:
                allocation[i] = share
            break
    return allocation


def load_arrivals(attempts_path: Path, sessions_path: Path) -> pd.DataFrame:
    attempts = pd.read_csv(attempts_path)
    sessions = pd.read_csv(sessions_path)
    att_cols = {"arrival_id", "site_id", "start_time", "requested_energy_kwh"}
    ses_cols = {"arrival_id", "requested_power_kw", "duration_minutes"}
    if att_cols - set(attempts.columns) or ses_cols - set(sessions.columns):
        raise ValueError("Arrival/session files are missing required columns")
    if attempts["arrival_id"].duplicated().any() or sessions["arrival_id"].duplicated().any():
        raise ValueError("arrival_id must be unique in attempts and sessions")
    attempts = attempts.merge(
        sessions[["arrival_id", "requested_power_kw", "duration_minutes"]],
        on="arrival_id", how="left", validate="one_to_one"
    )
    attempts["start_time"] = pd.to_datetime(attempts["start_time"], errors="raise").dt.floor("min")
    attempts["requested_energy_kwh"] = pd.to_numeric(attempts["requested_energy_kwh"], errors="coerce")
    attempts["requested_power_kw"] = pd.to_numeric(attempts["requested_power_kw"], errors="coerce")
    attempts["duration_minutes"] = pd.to_numeric(attempts["duration_minutes"], errors="coerce")
    if attempts[["site_id", "start_time", "requested_energy_kwh"]].isna().any().any():
        raise ValueError("Arrival site/time/requested energy missing")
    if (attempts["requested_energy_kwh"] <= 0).any() or len(attempts) == 0:
        raise ValueError("Arrival energies must be positive; data cannot be empty")
    attempts = attempts.sort_values(["site_id", "start_time", "arrival_id"]).reset_index(drop=True)

    # Historical rejected cars did not record vehicle power/stay. Impute from
    # served cars at the SAME site, with a fixed random seed for reproducibility.
    rng = np.random.default_rng(RANDOM_SEED)
    for site_id, group in attempts.groupby("site_id", sort=True):
        observed = group["requested_power_kw"].dropna()
        observed = observed[observed > 0]
        if observed.empty:
            raise ValueError(f"No observed positive car power for {site_id}; cannot impute")
        missing = group.index[attempts.loc[group.index, "requested_power_kw"].isna()]
        if len(missing):
            attempts.loc[missing, "requested_power_kw"] = rng.choice(observed.to_numpy(), size=len(missing))
    if (attempts["requested_power_kw"] <= 0).any():
        raise ValueError("Invalid vehicle requested power")
    missing_stays = attempts["duration_minutes"].isna()
    attempts.loc[missing_stays, "duration_minutes"] = (
        attempts.loc[missing_stays, "requested_energy_kwh"] * 60 /
        attempts.loc[missing_stays, "requested_power_kw"]
    ).clip(upper=60)
    if (attempts["duration_minutes"] <= 0).any():
        raise ValueError("Invalid vehicle stay times")
    attempts["max_stay_min"] = np.minimum(
        MAX_STAY_MINUTES,
        np.maximum(1, np.ceil(attempts["duration_minutes"] * MAX_STAY_MULTIPLIER))
    ).astype(int)
    return attempts


@dataclass
class Vehicle:
    remaining_kwh: float
    requested_kw: float
    max_stay_min: int
    occupied_min: int = 0


@dataclass
class Unit:
    group_id: str
    rated_kw: float
    connector_kw: float
    simultaneous_positions: int
    connector_count: int
    pool_id: str
    slots: list[Vehicle | None] = field(default_factory=list)

    def __post_init__(self):
        self.slots = [None] * self.simultaneous_positions

    @property
    def occupied(self) -> int:
        return sum(v is not None for v in self.slots)


def load_scenario_inputs(scenarios_path: Path, groups_path: Path, pools_path: Path):
    scenarios = read_required(
        scenarios_path,
        {"scenario_id", "site_id", "city", "scenario_type", "scenario_chargers",
         "scenario_connectors", "scenario_simultaneous_positions", "scenario_grid_kw",
         "other_site_load_kw", "grid_limit_source", "engineering_review_status"},
        "registry expansion scenarios"
    )
    group_configs = read_required(
        groups_path,
        {"scenario_id", "site_id", "charger_group_id", "scenario_units", "connectors_per_unit",
         "max_simultaneous_sessions_per_unit", "rated_unit_output_kw", "max_connector_output_kw",
         "shared_power_pool_id", "architecture", "evidence_status"},
        "registry scenario charger groups"
    )
    pools = read_required(
        pools_path,
        {"site_id", "shared_power_pool_id", "total_output_capacity_kw", "evidence_status"},
        "shared-power pools"
    )
    if scenarios.empty or group_configs.empty:
        raise ValueError("Scenario/group configuration is empty")
    if scenarios["scenario_id"].duplicated().any():
        raise ValueError("Duplicate scenario IDs")
    if group_configs.duplicated(["scenario_id", "charger_group_id"]).any():
        raise ValueError("Duplicate scenario group rows")
    scenarios_by_id = {row["scenario_id"]: row for _, row in scenarios.iterrows()}
    configurations: dict[str, list[dict]] = defaultdict(list)
    for _, row in group_configs.iterrows():
        sid = row["scenario_id"]
        if sid not in scenarios_by_id or row["site_id"] != scenarios_by_id[sid]["site_id"]:
            raise ValueError(f"Unknown scenario or site mismatch for charger group {sid}")
        key = f"{sid}/{row['charger_group_id']}"
        count = require_number(row["scenario_units"], f"{key}: units", zero_ok=True, integer=True)
        connectors = require_number(row["connectors_per_unit"], f"{key}: connectors", integer=True)
        positions = require_number(row["max_simultaneous_sessions_per_unit"], f"{key}: positions", integer=True)
        if positions > connectors:
            raise ValueError(f"{key}: sessions cannot exceed connectors")
        rated_kw = require_number(row["rated_unit_output_kw"], f"{key}: output")
        connector_kw = require_number(row["max_connector_output_kw"], f"{key}: connector output")
        architecture = row["architecture"].upper()
        if architecture not in {"INTEGRATED", "DISTRIBUTED"}:
            raise ValueError(f"{key}: invalid architecture {architecture}")
        pool_id = row["shared_power_pool_id"]
        if architecture == "DISTRIBUTED" and not pool_id:
            raise ValueError(f"{key}: distributed hardware requires shared power pool")
        if not row["evidence_status"]:
            raise ValueError(f"{key}: evidence status is missing")
        configurations[sid].append(dict(
            group_id=row["charger_group_id"], count=count, connectors=connectors,
            positions=positions, rated_kw=rated_kw, connector_kw=connector_kw,
            pool_id=pool_id, evidence_status=row["evidence_status"]
        ))
    pool_caps = {}
    for _, row in pools.iterrows():
        key = (row["site_id"], row["shared_power_pool_id"])
        if not all(key) or key in pool_caps:
            raise ValueError(f"Invalid or duplicate power pool: {key}")
        pool_caps[key] = require_number(row["total_output_capacity_kw"], f"power pool {key}")
    for sid, groups in configurations.items():
        s = scenarios_by_id[sid]
        units = sum(g["count"] for g in groups)
        connectors = sum(g["count"] * g["connectors"] for g in groups)
        positions = sum(g["count"] * g["positions"] for g in groups)
        if (units != require_number(s["scenario_chargers"], f"{sid}: scenario_chargers", integer=True)
            or connectors != require_number(s["scenario_connectors"], f"{sid}: scenario_connectors", integer=True)
            or positions != require_number(s["scenario_simultaneous_positions"], f"{sid}: scenario_positions", integer=True)):
            raise ValueError(f"Hardware totals do not match scenario {sid}")
        for g in groups:
            if g["pool_id"] and (s["site_id"], g["pool_id"]) not in pool_caps:
                raise ValueError(f"{sid} references missing shared pool {g['pool_id']}")
    return scenarios, configurations, pool_caps


def simulate_scenario(arrivals: pd.DataFrame, scenario: pd.Series,
                      groups: list[dict], pool_caps: dict) -> dict:
    site_id = scenario["site_id"]
    site_import_kw = require_number(scenario["scenario_grid_kw"], f"{site_id}: grid import")
    other_load = (
        require_number(scenario["other_site_load_kw"], f"{site_id}: other load", zero_ok=True)
        if str(scenario["other_site_load_kw"]).strip() else 0.0
    )
    if site_import_kw <= other_load:
        raise ValueError(f"{site_id}: grid import limit <= other loads")
    dc_budget_kw = (site_import_kw - other_load) * CHARGING_EFFICIENCY
    units: list[Unit] = []
    for group in sorted(groups, key=lambda x: x["group_id"]):
        units.extend(Unit(
            group_id=group["group_id"], rated_kw=group["rated_kw"],
            connector_kw=group["connector_kw"], simultaneous_positions=group["positions"],
            connector_count=group["connectors"], pool_id=group["pool_id"]
        ) for _ in range(group["count"]))
    if not units:
        raise ValueError(f"{site_id}: no charger units")
    events = list(arrivals[["start_time", "requested_energy_kwh", "requested_power_kw", "max_stay_min"]]
                  .itertuples(index=False, name=None))
    if not events:
        raise ValueError(f"{site_id}: missing arrivals")

    accepted = rejected = completed = 0
    occupied_sum = 0
    requested_accepted = energy_delivered = rejected_energy = 0.0
    at_grid_limit = 0
    at_pool_limit = 0
    peak_import = peak_dc = 0.0
    arrival_index = 0
    active = 0
    now = events[0][0]

    while arrival_index < len(events) or active:
        if not active and arrival_index < len(events):
            now = events[arrival_index][0]  # Jump across idle minutes.
        while arrival_index < len(events) and events[arrival_index][0] <= now:
            _, energy, vehicle_kw, max_stay = events[arrival_index]
            arrival_index += 1
            # Select a unit with the fewest active vehicles. For mixed groups,
            # prefer more connector-level headroom when occupancy is tied.
            eligible = [
                (u.occupied, -min(u.connector_kw, u.rated_kw), idx)
                for idx, u in enumerate(units) if u.occupied < u.simultaneous_positions
            ]
            if not eligible:
                rejected += 1
                rejected_energy += float(energy)
                continue
            _, _, idx = min(eligible)
            u = units[idx]
            slot = u.slots.index(None)
            u.slots[slot] = Vehicle(float(energy), float(vehicle_kw), int(max_stay))
            accepted += 1
            active += 1
            requested_accepted += float(energy)

        vehicles: list[Vehicle] = []
        local_caps: list[float] = []
        pools_for_car: list[str] = []
        for u in units:
            local_vehicles = [v for v in u.slots if v is not None]
            limits = [min(u.connector_kw, v.requested_kw) for v in local_vehicles]
            local_allocations = fair_allocation(limits, u.rated_kw)
            vehicles.extend(local_vehicles)
            local_caps.extend(local_allocations)
            pools_for_car.extend([u.pool_id] * len(local_vehicles))

        # Enforce centrally shared DC power-unit limits by pool, then grid.
        pool_adjusted = local_caps.copy()
        pool_indices: dict[str, list[int]] = defaultdict(list)
        for i, pool_id in enumerate(pools_for_car):
            if pool_id:
                pool_indices[pool_id].append(i)
        for pool_id, indices in pool_indices.items():
            budget = pool_caps[(site_id, pool_id)]
            allocated = fair_allocation([pool_adjusted[i] for i in indices], budget)
            if sum(pool_adjusted[i] for i in indices) > budget + EPS:
                at_pool_limit += 1
            for i, kw in zip(indices, allocated):
                pool_adjusted[i] = kw
        allocation = fair_allocation(pool_adjusted, dc_budget_kw)
        actual_dc = 0.0
        for vehicle, power in zip(vehicles, allocation):
            delivered = min(vehicle.remaining_kwh, power / 60.0)
            vehicle.remaining_kwh -= delivered
            vehicle.occupied_min += 1
            energy_delivered += delivered
            actual_dc += delivered * 60.0
        grid_import = actual_dc / CHARGING_EFFICIENCY + other_load
        peak_dc = max(peak_dc, actual_dc)
        peak_import = max(peak_import, grid_import)
        if grid_import > site_import_kw + 0.01:
            raise AssertionError(f"{site_id}: site import exceeds grid limit")
        if grid_import >= site_import_kw - 0.01:
            at_grid_limit += 1
        # After one minute, completed/expired sessions release their positions.
        for u in units:
            for slot, vehicle in enumerate(u.slots):
                if vehicle is None:
                    continue
                if vehicle.remaining_kwh <= EPS or vehicle.occupied_min >= vehicle.max_stay_min:
                    completed += int(vehicle.remaining_kwh <= EPS)
                    occupied_sum += vehicle.occupied_min
                    u.slots[slot] = None
                    active -= 1
        now += MINUTE

    total_requested = float(arrivals["requested_energy_kwh"].sum())
    served_shortfall = max(0.0, requested_accepted - energy_delivered)
    total_unserved = rejected_energy + served_shortfall
    if accepted + rejected != len(events) or abs(total_unserved - (total_requested - energy_delivered)) > 0.1:
        raise AssertionError(f"{site_id}: invalid arrival/energy balance")
    return {
        "site_id": site_id,
        "city": scenario["city"],
        "scenario_id": scenario["scenario_id"],
        "scenario_type": scenario["scenario_type"],
        "scenario_chargers": len(units),
        "scenario_connectors": sum(u.connector_count for u in units),
        "scenario_simultaneous_positions": sum(u.simultaneous_positions for u in units),
        "grid_capacity_kw": round(site_import_kw, 3),
        "grid_source": scenario["grid_limit_source"],
        "other_site_load_assumed_zero": str(scenario["other_site_load_kw"]).strip() == "",
        "arrivals": len(events),
        "cars_served": accepted,
        "cars_rejected": rejected,
        "rejected_pct": round(rejected / len(events) * 100, 2),
        "cars_fully_charged": completed,
        "cars_fully_charged_pct": round(completed / accepted * 100, 2) if accepted else 0.0,
        "energy_requested_kwh": round(total_requested, 1),
        "energy_delivered_kwh": round(energy_delivered, 1),
        "energy_rejected_kwh": round(rejected_energy, 1),
        "energy_shortfall_served_kwh": round(served_shortfall, 1),
        "total_unserved_energy_kwh": round(total_unserved, 1),
        "average_occupied_minutes": round(occupied_sum / accepted, 1) if accepted else 0.0,
        "average_charging_power_kw": round(60 * energy_delivered / occupied_sum, 1) if occupied_sum else 0.0,
        "peak_site_grid_draw_kw": round(peak_import, 2),
        "peak_dc_output_kw": round(peak_dc, 2),
        "minutes_at_grid_limit": at_grid_limit,
        "minutes_shared_pool_limited": at_pool_limit,
        "investment_readiness": "DEMO_ONLY_ENGINEERING_SCREEN",
    }




