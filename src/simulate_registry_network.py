def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--mode", choices=["synthetic", "observed"], default="synthetic",
                        help="Synthetic arrival simulation (unchanged) or real recorded-session checks")
    parser.add_argument("--observed-sessions", type=Path, default=OUT / "cpo_real_observed_sessions.csv")
    parser.add_argument("--observed-summary-output", type=Path, default=OUT / "cpo_real_observed_capacity_summary.csv")
    parser.add_argument("--observed-scenario-output", type=Path, default=OUT / "cpo_real_observed_scenario_checks.csv")
    parser.add_argument("--scenarios", type=Path, default=OUT / "registry_network_expansion_scenarios.csv")
    parser.add_argument("--scenario-groups", type=Path, default=OUT / "registry_scenario_charger_groups.csv")
    parser.add_argument("--pools", type=Path, default=CFG / "cpo_shared_power_pools.csv")
    parser.add_argument("--attempts", type=Path, default=RAW / "demand_attempts.csv")
    parser.add_argument("--sessions", type=Path, default=RAW / "charging_sessions.csv")
    parser.add_argument("--output", type=Path, default=OUT / "registry_network_simulation_results.csv")
    parser.add_argument("--impact-output", type=Path, default=OUT / "registry_network_simulation_impact.csv")
    parser.add_argument("--site-id", type=str, default=None, help="Optional one-site validation run")
    args = parser.parse_args()
    if args.mode == "observed":
        observed_mode(args)
        return
    scenarios, configs, pools = load_scenario_inputs(args.scenarios, args.scenario_groups, args.pools)
    if args.site_id:
        scenarios = scenarios[scenarios["site_id"] == args.site_id].copy()
        if scenarios.empty:
            raise ValueError(f"Site {args.site_id} is not in the scenario catalog")
    arrivals = load_arrivals(args.attempts, args.sessions)
    results = []
    total = len(scenarios)
    print("\n--- REGISTRY-AWARE CPO NETWORK SIMULATION ---")
    print(f"Sites: {scenarios.site_id.nunique()} | Scenarios: {total} | Hardware groups: {len(set((s, g['group_id']) for sid, gs in configs.items() for g in gs for s in [sid]))}")
    for i, (_, scenario) in enumerate(scenarios.iterrows(), start=1):
        site_data = arrivals[arrivals["site_id"] == scenario["site_id"]]
        if site_data.empty:
            raise ValueError(f"{scenario['site_id']}: no arrival data")
        print(f"[{i}/{total}] {scenario['city']} — {scenario['scenario_chargers']} units / {scenario['scenario_simultaneous_positions']} sessions / {scenario['scenario_grid_kw']} kW")
        results.append(simulate_scenario(site_data, scenario, configs[scenario["scenario_id"]], pools))
    result_frame = pd.DataFrame(results)
    impact_rows = []
    for site_id, group in result_frame.groupby("site_id"):
        baseline = group[group["scenario_type"] == "CURRENT"]
        if len(baseline) != 1:
            raise ValueError(f"{site_id} needs exactly one CURRENT scenario")
        base = baseline.iloc[0]
        for _, item in group.iterrows():
            impact_rows.append({
                "site_id": site_id,
                "city": item["city"],
                "scenario_id": item["scenario_id"],
                "scenario_type": item["scenario_type"],
                "scenario_chargers": item["scenario_chargers"],
                "scenario_connectors": item["scenario_connectors"],
                "additional_cars_served": int(item["cars_served"] - base["cars_served"]),
                "additional_energy_delivered_kwh": round(item["energy_delivered_kwh"] - base["energy_delivered_kwh"], 1),
                "change_in_total_unserved_energy_kwh": round(item["total_unserved_energy_kwh"] - base["total_unserved_energy_kwh"], 1),
                "minutes_at_grid_limit": int(item["minutes_at_grid_limit"]),
                "investment_readiness": item["investment_readiness"],
            })
    impact_frame = pd.DataFrame(impact_rows)
    if args.output.resolve() == args.impact_output.resolve():
        raise ValueError("Output CSVs need distinct paths")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.impact_output.parent.mkdir(parents=True, exist_ok=True)
    result_frame.to_csv(args.output, index=False)
    impact_frame.to_csv(args.impact_output, index=False)

    print("\n--- GROUP-AWARE NETWORK IMPACT ---")
    print(impact_frame[["city", "scenario_type", "scenario_chargers", "scenario_connectors",
                        "additional_cars_served", "additional_energy_delivered_kwh",
                        "minutes_at_grid_limit"]].to_string(index=False))
    print(f"\nSaved: {args.output}")
    print(f"Saved: {args.impact_output}")
    print("TECHNICAL DEMO ONLY: charging curves, customer waiting, equipment failure and verified site constraints not yet modeled.")
    print("No investment conclusions. Grid capacity is the supplied input, not a DSO-validated upgrade.")


if __name__ == "__main__":
    main()
