    if args.observed_summary_output.resolve() == args.observed_scenario_output.resolve():
        raise ValueError("Observed summary and comparison output paths must differ")
    if args.observed_summary_output.resolve() in {
        args.output.resolve(), args.impact_output.resolve()
    } or args.observed_scenario_output.resolve() in {
        args.output.resolve(), args.impact_output.resolve()
    }:
        raise ValueError("Observed mode cannot overwrite synthetic simulation outputs")
    summary.to_csv(args.observed_summary_output, index=False)
