r"""Prepare operator-specific evidence intake and the network's next-action queue.

Run in your CPO Network Development project directory (Windows CMD):
    python src\prepare_cpo_operator_evidence_intake.py

Input files already generated by the project:
    data/processed/cpo_network_technical_decisions.csv
    data/config/cpo_market_evidence_2026.json

Outputs:
    data/config/cpo_operator_evidence_intake.csv  (editable; NEVER overwritten)
    data/processed/cpo_operator_evidence_gaps.csv
    data/processed/cpo_workflow_action_queue.csv

IMPORTANT: This is a document/data collection workflow, NOT a financial
investment recommendation. The project uses synthetic site arrivals and
unverified long-term demand. Never treat the presence of a value as proof
that the underlying data are correct or that grid construction is approved.
"""

from __future__ import annotations

import json
import math
from datetime import date
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
CONFIG = ROOT / "data" / "config"
PROCESSED = ROOT / "data" / "processed"
TECHNICAL_CSV = PROCESSED / "cpo_network_technical_decisions.csv"
MARKET_JSON = CONFIG / "cpo_market_evidence_2026.json"
INTAKE_CSV = CONFIG / "cpo_operator_evidence_intake.csv"
GAPS_CSV = PROCESSED / "cpo_operator_evidence_gaps.csv"
QUEUE_CSV = PROCESSED / "cpo_workflow_action_queue.csv"

INTAKE_COLUMNS = [
    "site_id", "city", "required_input", "value", "unit", "source_type",
    "source_reference", "as_of", "review_status", "notes",
]
TECHNICAL_COLUMNS = [
    "site_id", "city", "planning_year", "assumed_annual_arrival_growth_pct",
    "current_chargers", "shortlisted_chargers", "additional_chargers",
    "rejection_pct_current", "rejection_pct_shortlisted",
    "technical_next_action", "site_feasibility_gate",
]
SOURCE_TYPES = {"OPERATOR_DATA", "ESTIMATE_QUOTE", "VENDOR_SPEC", "LAW_STANDARD"}


def unit_for(field: str) -> str:
    if field.endswith("_eur_per_kwh"):
        return "EUR/kWh"
    if field.endswith("_eur_per_kw_year"):
        return "EUR/(kW*year)"
    if field.endswith("_eur_year"):
        return "EUR/year"
    if field.endswith("_eur"):
        return "EUR"
    if field.endswith("_kw"):
        return "kW"
    return "TEXT/REFERENCE"


def read_required_inputs() -> list[str]:
    if not MARKET_JSON.is_file():
        raise FileNotFoundError(f"Missing reference: {MARKET_JSON}")
    with MARKET_JSON.open("r", encoding="utf-8") as handle:
        obj = json.load(handle)
    required = obj.get("site_specific_inputs_required", {})
    if not isinstance(required, dict) or not required:
        raise ValueError("Market JSON must contain site_specific_inputs_required")
    return list(required)


def read_technical() -> pd.DataFrame:
    if not TECHNICAL_CSV.is_file():
        raise FileNotFoundError(
            f"Missing technical decisions: {TECHNICAL_CSV}\n"
            "First run: python src\\build_cpo_technical_decision_table.py"
        )
    df = pd.read_csv(TECHNICAL_CSV, dtype={"site_id": "string"})
    df.columns = df.columns.str.strip()
    missing = set(TECHNICAL_COLUMNS) - set(df.columns)
    if missing:
        raise ValueError(f"Technical decision file missing: {sorted(missing)}")
    if df.empty:
        raise ValueError("Technical decision file has no rows")
    df["site_id"] = df["site_id"].astype("string").str.strip()
    df["city"] = df["city"].astype("string").str.strip()
    if df["site_id"].isna().any() or df["site_id"].eq("").any():
        raise ValueError("Missing site_id")
    if df["city"].isna().any() or df["city"].eq("").any():
        raise ValueError("Missing city")
    if df.groupby("site_id")["city"].nunique().gt(1).any():
        raise ValueError("A site has conflicting city labels")
    for field in (
        "planning_year", "assumed_annual_arrival_growth_pct",
        "current_chargers", "rejection_pct_current",
    ):
        df[field] = pd.to_numeric(df[field], errors="raise")
        if df[field].isna().any() or not df[field].map(math.isfinite).all():
            raise ValueError(f"Invalid {field}")
    if df.duplicated(
        ["site_id", "planning_year", "assumed_annual_arrival_growth_pct"]
    ).any():
        raise ValueError("Duplicate site/year/demand scenario in decisions")
    return df


def build_template(df: pd.DataFrame, required: list[str]) -> pd.DataFrame:
    sites = df[["site_id", "city"]].drop_duplicates().sort_values("site_id")
    records = []
    for site in sites.itertuples(index=False):
        for field in required:
            records.append({
                "site_id": str(site.site_id),
                "city": str(site.city),
                "required_input": field,
                "value": "",
                "unit": unit_for(field),
                "source_type": "",
                "source_reference": "",
                "as_of": "",
                "review_status": "MISSING",
                "notes": "",
            })
    return pd.DataFrame(records, columns=INTAKE_COLUMNS)


def preserve_existing(template: pd.DataFrame) -> tuple[pd.DataFrame, int]:
    """Don't overwrite user-entered data. Append new site/field pairs only."""
    if not INTAKE_CSV.exists():
        CONFIG.mkdir(parents=True, exist_ok=True)
        template.to_csv(INTAKE_CSV, index=False)
        return template, len(template)

    existing = pd.read_csv(INTAKE_CSV, dtype=str, keep_default_na=False)
    existing.columns = existing.columns.str.strip()
    missing = set(INTAKE_COLUMNS) - set(existing.columns)
    if missing:
        raise ValueError(
            f"Existing intake file missing columns {sorted(missing)}. "
            "Back it up; do not delete your entered evidence."
        )
    if existing.duplicated(["site_id", "required_input"]).any():
        raise ValueError("Duplicate site_id + required_input in intake file")
    known = set(zip(existing["site_id"], existing["required_input"]))
    new = template[
        ~pd.Series(
            list(zip(template["site_id"], template["required_input"])),
            index=template.index,
        ).isin(known)
    ]
    if not new.empty:
        result = pd.concat([existing, new], ignore_index=True)
        result.to_csv(INTAKE_CSV, index=False)
        return result, len(new)
    return existing, 0


def documented(row: pd.Series) -> bool:
    value = str(row["value"]).strip()
    source_type = str(row["source_type"]).strip()
    reference = str(row["source_reference"]).strip()
    as_of = str(row["as_of"]).strip()
    if not value or not reference or source_type not in SOURCE_TYPES or not as_of:
        return False
    try:
        entered_date = date.fromisoformat(as_of)
    except ValueError:
        return False
    return entered_date <= date.today()


def make_outputs(
    decisions: pd.DataFrame, intake: pd.DataFrame, required: list[str]
) -> tuple[pd.DataFrame, pd.DataFrame]:
    # Inspect only inputs for the sites present in the technical decisions.
    sites = decisions[["site_id", "city"]].drop_duplicates()
    expected = {(str(s.site_id), field) for s in sites.itertuples(index=False) for field in required}
    applicable = intake.loc[
        intake.apply(
            lambda r: (str(r["site_id"]).strip(), str(r["required_input"]).strip()) in expected,
            axis=1,
        )
    ].copy()
    applicable["has_documented_source"] = applicable.apply(documented, axis=1)
    # Source documented != verified by operator; review_status remains a manual step.
    applicable["gap_reason"] = applicable.apply(
        lambda r: (
            "PENDING_OPERATOR_TECHNICAL_AND_COMMERCIAL_REVIEW"
            if bool(r["has_documented_source"])
            else "MISSING_VALUE_OR_SOURCE_OR_DATE"
        ),
        axis=1,
    )
    gaps = applicable.loc[~applicable["has_documented_source"], [
        "site_id", "city", "required_input", "unit", "gap_reason"
    ]].copy()

    counts = applicable.groupby("site_id")["has_documented_source"].agg(
        evidence_fields_present="sum", evidence_fields_total="count"
    ).reset_index()
    decisions_out = decisions.merge(counts, on="site_id", how="left", validate="many_to_one")
    if decisions_out["evidence_fields_total"].isna().any():
        raise ValueError("Site missing from evidence intake")
    if (decisions_out["evidence_fields_total"] != len(required)).any():
        raise ValueError("Evidence intake does not have exactly one row per required site input")
    decisions_out["evidence_fields_missing"] = (
        decisions_out["evidence_fields_total"] - decisions_out["evidence_fields_present"]
    )

    def next_step(action: str) -> str:
        return {
            "MONITOR_CURRENT_SITE": "MONITOR_AND_VALIDATE_SITE_DEMAND",
            "VERIFY_EXPANSION_SITE_AND_EQUIPMENT": "REQUEST_SITE_AND_EQUIPMENT_FEASIBILITY",
            "REVIEW_LOAD_MANAGEMENT_AND_GRID_LIMIT": "REQUEST_DSO_AND_LOAD_MANAGEMENT_REVIEW",
            "TEST_ADDITIONAL_CHARGER_OPTIONS": "EXPAND_HARDWARE_SCENARIO_SEARCH",
        }.get(str(action).strip(), "REVIEW_TECHNICAL_SCREEN")

    decisions_out["next_workflow_step"] = decisions_out["technical_next_action"].map(next_step)
    decisions_out["finance_gate"] = "BLOCKED_UNVERIFIED_DEMAND_AND_SITE_FINANCIALS"
    decisions_out["investment_decision"] = "NOT_ASSESSED"
    decisions_out["evidence_basis"] = "SYNTHETIC_DEMO"
    select = [
        "site_id", "city", "planning_year", "assumed_annual_arrival_growth_pct",
        "current_chargers", "shortlisted_chargers", "additional_chargers",
        "rejection_pct_current", "rejection_pct_shortlisted",
        "technical_next_action", "next_workflow_step", "evidence_fields_present",
        "evidence_fields_missing", "evidence_fields_total", "finance_gate",
        "investment_decision", "evidence_basis", "site_feasibility_gate",
    ]
    return gaps, decisions_out[select].copy()


def main() -> None:
    decisions = read_technical()
    required = read_required_inputs()
    template = build_template(decisions, required)
    intake, appended = preserve_existing(template)
    gaps, action_queue = make_outputs(decisions, intake, required)

    PROCESSED.mkdir(parents=True, exist_ok=True)
    gaps.to_csv(GAPS_CSV, index=False)
    action_queue.to_csv(QUEUE_CSV, index=False)

    print("\n--- CPO OPERATOR EVIDENCE / ACTION QUEUE ---")
    print(
        f"Sites: {decisions.site_id.nunique()} | Technical demand cases: {len(action_queue)} "
        f"| Required inputs per site: {len(required)}"
    )
    print(f"New input rows appended without deleting existing entries: {appended}")
    print(action_queue[[
        "city", "assumed_annual_arrival_growth_pct", "current_chargers",
        "shortlisted_chargers", "next_workflow_step", "evidence_fields_missing",
    ]].to_string(index=False))
    print("\nAll finance decisions remain BLOCKED until real demand, costs and technical evidence are verified.")
    print(f"Editable intake: {INTAKE_CSV}")
    print(f"Missing evidence: {GAPS_CSV}")
    print(f"Workflow actions: {QUEUE_CSV}")


if __name__ == "__main__":
    main()
